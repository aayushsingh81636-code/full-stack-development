//trim method replace the whitespace characters of both sides of the string
let a="     Aayush singh     ";
let b=a.trim();
console.log(b);
//trimStart method replace the whitespaces from the start only
let c=a.trimStart();
console.log(c);
//trimEnd method replace the whitespaces form the end only
let d="      aoehpoawpoje      ";
let e=d.trimEnd();
console.log(e);
